/// Retrieve the 8-row glyph bitmap for a given ASCII char.
/// Returns None if the character is outside printable ASCII range (32..=126).
#[inline]
pub fn get_glyph(c: char) -> Option<&'static [u8; 8]> {
    let code = c as u32;
    if (32..=126).contains(&code) {
        Some(&FONT_8X8[(code - 32) as usize])
    } else {
        None
    }
}
