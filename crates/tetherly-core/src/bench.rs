/// Fail-closed validator and guardrails for the link throughput benchmark pipeline.
pub struct BenchValidator;

impl BenchValidator {
    /// Wire-budget cap shared with camera/mic (see `crate::wire`).
    pub const MAX_CHUNK_BYTES: usize = crate::wire::MAX_WIRE_CHUNK_BYTES;
    pub const MIN_CHUNK_BYTES: usize = 1024;
    pub const MIN_DURATION_SECS: u32 = 1;
    pub const MAX_DURATION_SECS: u32 = 60;

    /// Validates session identifier (1..=64 chars, ASCII alphanumeric, hyphens, and underscores).
    pub fn validate_session_id(id: &str) -> Result<String, CoreError> {
        let trimmed = id.trim();
        if trimmed.is_empty() || trimmed.len() > 64 {
            return Err(CoreError::InvalidPayload(
                "session_id length must be between 1 and 64 characters".to_string(),
            ));
        }
        if !trimmed
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        {
            return Err(CoreError::InvalidPayload(
                "session_id contains invalid characters".to_string(),
            ));
        }
        Ok(trimmed.to_string())
    }

    /// Sanitizes reason text, truncating to 64 bytes and removing ASCII control characters.
    pub fn sanitize_reason(reason: &str) -> String {
        let clean: String = reason
            .chars()
            .filter(|c| !c.is_ascii_control())
            .take(64)
            .collect();
        clean.trim().to_string()
    }

    /// Clamps benchmark duration to 1..=60 seconds.
    pub fn clamp_duration(duration_secs: u32) -> u32 {
        duration_secs.clamp(Self::MIN_DURATION_SECS, Self::MAX_DURATION_SECS)
    }

    /// Clamps chunk size to 1024..=65536 bytes.
    pub fn clamp_chunk_size(chunk_size: u32) -> u32 {
        chunk_size.clamp(Self::MIN_CHUNK_BYTES as u32, Self::MAX_CHUNK_BYTES as u32)
    }

    /// Validates benchmark data chunk bounds.
    pub fn validate_chunk(data: &[u8]) -> Result<(), CoreError> {
        if data.is_empty() {
            return Err(CoreError::InvalidPayload(
                "bench chunk must not be empty".to_string(),
            ));
        }
        if data.len() > Self::MAX_CHUNK_BYTES {
            return Err(CoreError::PayloadTooLarge);
        }
        Ok(())
    }

    /// Validates an entire benchmark request frame.
    pub fn validate_request(frame: &BenchRequestFrame) -> Result<(), CoreError> {
        Self::validate_session_id(&frame.session_id)?;
        if frame.peer_id.trim().is_empty() {
            return Err(CoreError::InvalidPayload(
                "peer_id cannot be empty".to_string(),
            ));
        }
        if !(Self::MIN_DURATION_SECS..=Self::MAX_DURATION_SECS).contains(&frame.duration_secs) {
            return Err(CoreError::InvalidPayload(
                "duration_secs must be between 1 and 60".to_string(),
            ));
        }
        if (frame.chunk_size as usize) < Self::MIN_CHUNK_BYTES
            || (frame.chunk_size as usize) > Self::MAX_CHUNK_BYTES
        {
            return Err(CoreError::InvalidPayload(
                "chunk_size must be between 1024 and 65536".to_string(),
            ));
        }
        Ok(())
    }

    /// Validates a benchmark data chunk frame.
    pub fn validate_data_frame(frame: &BenchDataFrame) -> Result<(), CoreError> {
        Self::validate_session_id(&frame.session_id)?;
        Self::validate_chunk(&frame.data)?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_bench_direction_and_role_strings() {
        assert_eq!(BenchDirection::Push.as_str(), "push");
        assert_eq!(BenchDirection::Pull.as_str(), "pull");
        assert_eq!(
            BenchDirection::from_str_lenient("download"),
            BenchDirection::Pull
        );
        assert_eq!(BenchDirection::from_str_lenient("rx"), BenchDirection::Pull);
        assert_eq!(
            BenchDirection::from_str_lenient("unknown"),
            BenchDirection::Push
        );
        assert_eq!(BenchRole::Initiator.as_str(), "initiator");
        assert_eq!(BenchRole::Responder.as_str(), "responder");
    }

    #[test]
    fn test_bench_validator_clamps_and_cleaning() {
        assert_eq!(BenchValidator::clamp_duration(0), 1);
        assert_eq!(BenchValidator::clamp_duration(30), 30);
        assert_eq!(BenchValidator::clamp_duration(3600), 60);
        assert_eq!(BenchValidator::clamp_chunk_size(0), 1024);
        assert_eq!(BenchValidator::clamp_chunk_size(16384), 16384);
        assert_eq!(BenchValidator::clamp_chunk_size(999999), 32768);

        assert!(BenchValidator::validate_session_id("bench-1").is_ok());
        assert!(BenchValidator::validate_session_id("").is_err());
        assert!(BenchValidator::validate_session_id("bad id!").is_err());
        assert_eq!(BenchValidator::sanitize_reason("a\nb\x7fc  "), "abc");

        assert!(BenchValidator::validate_chunk(&[0u8; 1024]).is_ok());
        assert!(BenchValidator::validate_chunk(&[]).is_err());
        let big = [0u8; BenchValidator::MAX_CHUNK_BYTES + 1];
        assert!(BenchValidator::validate_chunk(&big).is_err());
    }

    #[test]
    fn test_bench_validator_request() {
        let mut frame = BenchRequestFrame {
            session_id: "bench-sess-1".to_string(),
            peer_id: "tdev_peer".to_string(),
            direction: BenchDirection::Push,
            duration_secs: 5,
            chunk_size: 16384,
            timestamp_ms: 0,
        };
        assert!(BenchValidator::validate_request(&frame).is_ok());
        frame.duration_secs = 0;
        frame.chunk_size = 512;
        assert!(BenchValidator::validate_request(&frame).is_err());
        frame.duration_secs = 61;
        frame.chunk_size = 65536;
        assert!(BenchValidator::validate_request(&frame).is_err());
    }

    #[test]
    fn test_bench_frames_wire_roundtrip() {
        let request = BenchRequestFrame {
            session_id: "bench-1".to_string(),
            peer_id: "peer".to_string(),
            direction: BenchDirection::Pull,
            duration_secs: 10,
            chunk_size: 32768,
            timestamp_ms: 1000,
        };
        let decoded =
            BenchRequestFrame::from_payload(&request.to_frame().unwrap().payload).unwrap();
        assert_eq!(request, decoded);

        let accept = BenchAcceptFrame {
            session_id: "bench-1".to_string(),
            accepted: true,
            reject_reason: None,
            direction: BenchDirection::Pull,
            duration_secs: 10,
            chunk_size: 32768,
            timestamp_ms: 1001,
        };
        let decoded = BenchAcceptFrame::from_payload(&accept.to_frame().unwrap().payload).unwrap();
        assert_eq!(accept, decoded);

        let data = BenchDataFrame {
            session_id: "bench-1".to_string(),
            chunk_seq: 42,
            data: vec![7u8; 4096],
            timestamp_ms: 1002,
        };
        assert!(BenchValidator::validate_data_frame(&data).is_ok());
        let decoded = BenchDataFrame::from_payload(&data.to_frame().unwrap().payload).unwrap();
        assert_eq!(data, decoded);

        // Zero-copy encoder must interop with the owned decoder.
        let borrowed = BenchDataFrame::to_frame_for("bench-1", 42, &vec![7u8; 4096], 1002).unwrap();
        assert_eq!(borrowed.ty, data.to_frame().unwrap().ty);
        let decoded = BenchDataFrame::from_payload(&borrowed.payload).unwrap();
        assert_eq!(data, decoded);

        let report = BenchReportFrame {
            session_id: "bench-1".to_string(),
            direction: BenchDirection::Pull,
            duration_ms: 10000,
            bytes_transferred: 12_582_912,
            chunks: 384,
            throughput_mbps: 10.05,
            avg_chunk_latency_us: 26041,
            jitter_us: 1234,
            stopped_early: None,
            timestamp_ms: 1003,
        };
        let decoded = BenchReportFrame::from_payload(&report.to_frame().unwrap().payload).unwrap();
        assert_eq!(report, decoded);
    }
}
